const { chromium } = require('playwright-core');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 1100 }, locale: 'ru-RU' });
  const page = await ctx.newPage();
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('https://piz.itop7.ru/login', { waitUntil: 'networkidle' });
  await page.fill('input[name=login]', 'csstest');
  await page.fill('input[name=password]', 'Css2026!');
  await Promise.all([page.waitForLoadState('networkidle'), page.click('button[type=submit]')]);
  await page.goto('https://piz.itop7.ru/', { waitUntil: 'networkidle' });
  const cssHref = await page.locator('link[rel=stylesheet]').getAttribute('href');
  console.log('css', cssHref);
  console.log('group btn', await page.locator('[data-nav-group-toggle]').evaluate(e=>{const s=getComputedStyle(e);return {bg:s.backgroundColor,border:s.borderTopWidth,color:s.color,font:s.fontSize}}));
  console.log('admin menu before', await page.locator('#admin-menu').evaluate(e=>{const s=getComputedStyle(e);return {display:s.display,pos:s.position,bg:s.backgroundColor,width:s.width}}));
  console.log('gear', await page.locator('.sidebar-user__gear .icon').evaluate(e=>{const s=getComputedStyle(e);return {w:s.width,h:s.height}}));
  await page.click('[data-nav-group-toggle]');
  console.log('group visible', await page.locator('#nav-more').isVisible());
  await page.click('[data-admin-menu-toggle]');
  console.log('admin menu after', await page.locator('#admin-menu').evaluate(e=>{const s=getComputedStyle(e);return {display:s.display,pos:s.position,bg:s.backgroundColor,width:s.width,left:s.left,bottom:s.bottom}}));
  console.log('admin items', await page.locator('#admin-menu').innerText());
  await page.screenshot({ path: 'temp/nav-fixed.png' });
  console.log('errors', errors);
  await browser.close();
})().catch(e=>{console.error('FATAL',e);process.exit(1);});
